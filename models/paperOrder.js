module.exports = (sequelize, DataTypes) =>
  sequelize.define(
    "PaperOrder",
    {
      id: {
        type: DataTypes.UUID,
        primaryKey: true,
        defaultValue: DataTypes.UUIDV4,
      },
      user_id: { type: DataTypes.STRING(128), allowNull: false },
      linked_position_id: DataTypes.UUID,
      basket_id: DataTypes.UUID,
      idempotency_key: DataTypes.STRING(100),
      symbol_key: { type: DataTypes.STRING(100), allowNull: false },
      display_symbol: { type: DataTypes.STRING(100), allowNull: false },
      underlying: { type: DataTypes.STRING(24), allowNull: false },
      expiry_date: { type: DataTypes.DATEONLY, allowNull: false },
      strike_price: { type: DataTypes.DECIMAL(12, 2), allowNull: false },
      option_type: { type: DataTypes.STRING(4), allowNull: false },
      lot_size: { type: DataTypes.INTEGER, allowNull: false },
      side: { type: DataTypes.STRING(4), allowNull: false },
      product_type: { type: DataTypes.STRING(8), allowNull: false },
      order_type: { type: DataTypes.STRING(16), allowNull: false },
      status: { type: DataTypes.STRING(20), allowNull: false },
      quantity: { type: DataTypes.INTEGER, allowNull: false },
      limit_price: DataTypes.DECIMAL(12, 2),
      trigger_price: DataTypes.DECIMAL(12, 2),
      fill_price: DataTypes.DECIMAL(12, 2),
      slippage_applied: { type: DataTypes.DECIMAL(10, 2), defaultValue: 0 },
      margin_reserved: { type: DataTypes.DECIMAL(16, 2), defaultValue: 0 },
      sl_price: DataTypes.DECIMAL(12, 2),
      target_price: DataTypes.DECIMAL(12, 2),
      planned_rr: { type: DataTypes.DECIMAL(8, 2), defaultValue: 0 },
      rejection_reason: DataTypes.STRING(500),
      placed_at: { type: DataTypes.DATE, defaultValue: DataTypes.NOW },
      executed_at: DataTypes.DATE,
    },
    {
      tableName: "paper_orders",
      underscored: true,
      createdAt: false,
      updatedAt: "updated_at",
      indexes: [
        { unique: true, fields: ["user_id", "idempotency_key"] },
        { fields: ["user_id", "status", "placed_at"] },
        { fields: ["symbol_key", "status", "order_type"] },
      ],
    },
  );
