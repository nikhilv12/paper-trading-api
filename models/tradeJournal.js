module.exports = (sequelize, DataTypes) =>
  sequelize.define(
    "TradeJournal",
    {
      id: {
        type: DataTypes.UUID,
        primaryKey: true,
        defaultValue: DataTypes.UUIDV4,
      },
      user_id: { type: DataTypes.STRING(128), allowNull: false },
      position_id: DataTypes.UUID,
      symbol_key: DataTypes.STRING(100),
      display_symbol: DataTypes.STRING(100),
      underlying: DataTypes.STRING(24),
      option_type: DataTypes.STRING(4),
      direction: DataTypes.STRING(8),
      product_type: DataTypes.STRING(8),
      entry_time: DataTypes.DATE,
      exit_time: DataTypes.DATE,
      holding_seconds: DataTypes.INTEGER,
      quantity: DataTypes.INTEGER,
      entry_price: DataTypes.DECIMAL(12, 2),
      exit_price: DataTypes.DECIMAL(12, 2),
      initial_sl: DataTypes.DECIMAL(12, 2),
      initial_target: DataTypes.DECIMAL(12, 2),
      planned_rr: DataTypes.DECIMAL(8, 2),
      realized_r: DataTypes.DECIMAL(10, 2),
      gross_pnl: DataTypes.DECIMAL(16, 2),
      charges_breakdown: DataTypes.TEXT,
      total_charges: DataTypes.DECIMAL(14, 2),
      net_pnl: DataTypes.DECIMAL(16, 2),
      ai_flags: { type: DataTypes.TEXT, defaultValue: "[]" },
      setup_tag: { type: DataTypes.STRING(40), defaultValue: "Unclassified" },
      emotion_tag: { type: DataTypes.STRING(40), defaultValue: "Neutral" },
      user_notes: DataTypes.TEXT,
    },
    {
      tableName: "paper_trade_journal",
      underscored: true,
      updatedAt: false,
      createdAt: "created_at",
      indexes: [{ fields: ["user_id", "exit_time"] }],
    },
  );
